def render_typescript(data: dict) -> str:
    """Typed scalar forwarding only; no kernel decisions are reproduced in JS."""
    types = {"uint8_t": "number", "uint32_t": "number", "uint64_t": "bigint"}
    widths = {"uint8_t": 8, "uint32_t": 32, "uint64_t": 64}
    runtime = "__orbAbiRuntime"
    names = {p["name"] for fn in data["functions"] for p in fn["params"]}
    while runtime in names:
        runtime += "_"
    asset = ROOT / "orb/src/assets/orb_kernel.wasm"
    digest = hashlib.sha256(asset.read_bytes()).hexdigest()
    out = ["// Generated by scripts/gen_kernel_bindings.py. Do not edit.",
           f'import * as {runtime} from "./orbKernelRuntime";',
           'import kernelUrl from "./assets/orb_kernel.wasm?url";',
           f'export const kernelSha256 = "{digest}";',
           "export const kernelArities: Record<string, number> = " +
           json.dumps({f["name"]: len(f["params"]) for f in data["functions"]}, indent=2) + ";",
           "export async function initializeKernel(bytes?: Uint8Array): Promise<void> {",
           "  if (!bytes) {",
           "    const response = await fetch(kernelUrl);",
           '    if (!response.ok) throw new Error("Shared kernel download failed");',
           "    bytes = new Uint8Array(await response.arrayBuffer());",
           "  }",
           f"  await {runtime}.loadKernel(bytes, kernelSha256, kernelArities);",
           "}", "export const kernelAbi = {"]
    for fn in data["functions"]:
        params = ", ".join(f'{p["name"]}: {types[p["type"]]}' for p in fn["params"])
        args = ", ".join(f'{runtime}.word({p["name"]}, {widths[p["type"]]})' for p in fn["params"])
        result = "result64" if fn["ret"] == "uint64_t" else "result32"
        out += [f'  {fn["name"]}({params}): {types[fn["ret"]]} {{',
                f'    return {runtime}.{result}({runtime}.callKernel("{fn["name"]}", [{args}]));', "  },"]
    return "\n".join([*out, "};", ""])


