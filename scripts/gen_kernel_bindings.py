def render_typescript(data: dict) -> str:
    """Typed scalar forwarding only; no kernel decisions are reproduced in JS."""
    types = {"uint8_t": "number", "uint32_t": "number", "uint64_t": "bigint"}
    widths = {"uint8_t": 8, "uint32_t": 32, "uint64_t": 64}
    runtime = "__orbAbiRuntime"
    names = {p["name"] for fn in data["functions"] for p in fn["params"]}
    while runtime in names:
        runtime += "_"
    asset = ROOT / "orb/src/assets/orb_kernel.wasm"
    digest = hashlib.sha256(asset.read_bytes()).hexdigest()
    specs = {f["name"]: ([widths[p["type"]] for p in f["params"]], 1 if f["ret"] == "uint64_t" else 0) for f in data["functions"]}
    out = [
        "// Generated by scripts/gen_kernel_bindings.py. Do not edit.",
        f'import * as {runtime} from "./orbKernelRuntime";',
        'import kernelUrl from "./assets/orb_kernel.wasm?url";',
        f'export const kernelSha256 = "{digest}";',
        f"const _R = {runtime}, _S: Record<string, [readonly (8 | 32 | 64)[], 0 | 1]> = " + json.dumps(specs) + ";",
        "export const kernelArities: Record<string, number> = Object.fromEntries(Object.entries(_S).map(([k, [w]]) => [k, w.length]));",
        "export async function initializeKernel(bytes?: Uint8Array): Promise<void> {",
        "  if (!bytes) {",
        "    const response = await fetch(kernelUrl);",
        '    if (!response.ok) throw new Error("Shared kernel download failed");',
        "    bytes = new Uint8Array(await response.arrayBuffer());",
        "  }",
        "  await _R.loadKernel(bytes, kernelSha256, kernelArities);",
        "}",
        "export type KernelAbi = {",
    ]
    for fn in data["functions"]:
        params = ", ".join(f'{p["name"]}: {types[p["type"]]}' for p in fn["params"])
        out.append(f'  {fn["name"]}({params}): {types[fn["ret"]]};')
    out += [
        "};",
        "export const kernelAbi = Object.fromEntries(Object.entries(_S).map(([k, [w, r]]) => [k, _R.bindKernelFn(k, w, r === 1)])) as unknown as KernelAbi;",
    ]
    return "\n".join([*out, ""])


def render_leannative_shim(data: dict) -> str:
    """Scalar C-ABI forwarding shim for LeanNative probe_* archives."""
    out = [
        "/* Generated by scripts/gen_kernel_bindings.py from kernel_abi.json. Do not edit. */",
        "#include <stddef.h>",
        "#include <stdint.h>",
        '#include "orb_kernel.h"',
        "",
        "void *__orb_leannative_unreachable_malloc(size_t n) {",
        "    (void)n;",
        "    __builtin_trap();",
        "}",
        "",
        "void *__orb_leannative_unreachable_memcpy(void *d, const void *s, size_t n) {",
        "    (void)d;",
        "    (void)s;",
        "    (void)n;",
        "    __builtin_trap();",
        "}",
        "",
    ]
    for fn in data["functions"]:
        if not fn["name"].startswith(("orb_", "leansys_")):
            continue
        params = "void" if not fn["params"] else ", ".join("uint64_t" for _ in fn["params"])
        out.append(f'extern uint64_t probe_{fn["name"]}({params});')
    out.append("")
    for fn in data["functions"]:
        name = fn["name"]
        ret = fn["ret"]
        params = (
            "void"
            if not fn["params"]
            else ", ".join(f'{p["type"]} a{i}' for i, p in enumerate(fn["params"]))
        )
        if name == "lp_orb_x2dspec_Orb_Kernel_accessStep___redArg":
            body = "return (uint32_t)probe_orb_access_step((uint64_t)a0, (uint64_t)a1, (uint64_t)a2, (uint64_t)a3, (uint64_t)a4, 0);"
        else:
            args = ", ".join(f"(uint64_t)a{i}" for i in range(len(fn["params"])))
            body = f"return ({ret})probe_{name}({args});"
        out.append(f"{ret} {name}({params}) {{ {body} }}")
    return "\n".join([*out, ""])


def outputs(data: dict) -> dict[Path, str]:
    res = {
        ROOT / "orb/src/orbKernelAbi.ts": render_typescript(data),
        ROOT / data["header"]: render_header(data),
        ROOT / data["jni"]["path"]: render_jni(data),
        ROOT / "shared/orb-spec/cabi/orb_kernel_exports.json":
            json.dumps({"exports": [f["name"] for f in data["functions"]]}, indent=2) + "\n",
        ROOT / "shared/orb-spec/cabi/orb_kernel_leannative_shim.c": render_leannative_shim(data),
    }
    if "swift" in data:
        res[ROOT / data["swift"]["path"]] = render_swift(data)
    if "kotlin" in data:
        res[ROOT / data["kotlin"]["path"]] = render_kotlin(data)
    return res


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = ap.parse_args(argv)
    try:
        data = load_manifest()
    except (ManifestError, KeyError) as e:
        print(f"kernel_abi.json: {e}", file=sys.stderr)
        return 2
    stale = []
    for path, text in outputs(data).items():
        rel = path.relative_to(ROOT)
        current = path.read_text() if path.exists() else None
        if current == text:
            continue
        if args.check:
            stale.append(str(rel))
        else:
            path.write_text(text)
            print(f"wrote {rel}")
    if stale:
        print("stale generated kernel bindings (run scripts/gen_kernel_bindings.py):", *stale, sep="\n  ", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
