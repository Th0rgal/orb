#!/usr/bin/env python3
"""Generate the `[ffi]` allowlist in `lean/turbo-lean.toml`.

turbo-lean's kernel gate rejects root-package `@[extern]` declarations unless the
project declares them as trusted FFI (`"Module=decl=c_symbol"`). Every Orb FFI
binding is a C shim checked into the repo, so the list is derived from the source
`@[extern "sym"]` attributes. Run with `--check` to fail when it is stale.
"""
import pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
LEAN = ROOT / "lean"
TOML = LEAN / "turbo-lean.toml"
EXTERN = re.compile(r'@\[extern\s+"([^"]+)"\]\s*(?:(?:private|protected|noncomputable|unsafe)\s+)*(?:opaque|def)\s+([^\s(:]+)')


def module_of(path: pathlib.Path) -> str:
    # Packages are `lean/<Pkg>/<Root>/...` or the root `lean/<Lib>/...`.
    rel = path.relative_to(LEAN).with_suffix("")
    parts = rel.parts
    if (LEAN / parts[0] / "lakefile.lean").exists():
        parts = parts[1:]
    return ".".join(parts)


def entries() -> list[str]:
    out = []
    for path in sorted(LEAN.rglob("*.lean")):
        if ".lake" in path.parts or "lean-sys" in path.parts:
            continue
        src = re.sub(r"/-.*?-/", "", path.read_text(), flags=re.S)
        if "@[extern" not in src:
            continue
        mod = module_of(path)
        # Track `namespace X` / `end X` to recover each declaration's full name.
        stack, pos = [], 0
        events = [(m.start(), "ns", m.group(1)) for m in re.finditer(r"^namespace\s+(\S+)", src, re.M)]
        events += [(m.start(), "end", m.group(1)) for m in re.finditer(r"^end\s+(\S+)\s*$", src, re.M)]
        events += [(m.start(), "ext", m) for m in EXTERN.finditer(src)]
        for _, kind, val in sorted(events, key=lambda e: e[0]):
            if kind == "ns":
                stack.append(val)
            elif kind == "end":
                if stack and stack[-1] == val:
                    stack.pop()
            else:
                sym, name = val.group(1), val.group(2)
                full = ".".join(stack + [name]) if stack else name
                out.append(f"{mod}={full}={sym}")
    return out


def render() -> str:
    body = "".join(f'  "{e}",\n' for e in entries())
    return (
        "# Generated by scripts/gen_turbo_lean_ffi.py; do not edit by hand.\n"
        "# Orb's own C shims, admitted by turbo-lean's kernel gate as trusted FFI.\n"
        "[ffi]\nallow = [\n" + body + "]\n"
    )


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        if not TOML.exists() or TOML.read_text() != text:
            sys.exit("lean/turbo-lean.toml is stale: run python3 scripts/gen_turbo_lean_ffi.py")
    else:
        TOML.write_text(text)
