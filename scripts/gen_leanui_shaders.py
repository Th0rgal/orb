#!/usr/bin/env python3
"""Compile repo-root GLSL shaders into embedded Vulkan 1.3 SPIR-V in LeanUI/Shaders.lean.

Run without arguments to regenerate `lean/OrbDesktop/LeanUI/Shaders.lean`.
Run with `--check` in CI to verify:
  1. Source SHA-256 hashes of `shaders/scene_sdf.glsl` and `shaders/blur_box.comp.glsl` match
     `lean/OrbDesktop/LeanUI/Shaders.lean` (fails on any unregenerated GLSL edit).
  2. Embedded SPIR-V word arrays are valid little-endian Vulkan 1.3 SPIR-V (magic 0x07230203,
     4-byte aligned, passing `spirv-val --target-env vulkan1.3` when available).
  3. All 3 shader stages compile cleanly with `glslangValidator -V --target-env vulkan1.3`
     when `glslangValidator` is available (and match byte-for-byte when the compiler version
     matches the generator recorded in `Shaders.lean`).
"""
import glob
import hashlib
import os
import pathlib
import re
import shutil
import struct
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
SHADERS_DIR = ROOT / "shaders"
OUT_LEAN = ROOT / "lean/OrbDesktop/LeanUI/Shaders.lean"

STAGES = [
    ("sceneSdfVertSpv", SHADERS_DIR / "scene_sdf.glsl", "vert", ["-DVERTEX_SHADER"]),
    ("sceneSdfFragSpv", SHADERS_DIR / "scene_sdf.glsl", "frag", ["-DFRAGMENT_SHADER"]),
    ("blurBoxCompSpv", SHADERS_DIR / "blur_box.comp.glsl", "comp", []),
]


def find_tool(name: str, nix_glob: str | None = None) -> str | None:
    env_override = os.environ.get(name.upper().replace("-", "_"))
    if env_override and pathlib.Path(env_override).is_file():
        return env_override
    found = shutil.which(name)
    if found:
        return found
    if nix_glob:
        matches = sorted(glob.glob(nix_glob))
        if matches:
            return matches[-1]
    return None


def tool_version(glslang: str) -> str:
    res = subprocess.run([glslang, "--version"], capture_output=True, text=True)
    text = (res.stdout or res.stderr or "").strip()
    for line in text.splitlines():
        if "Glslang Version" in line:
            return line.strip()
    return text.splitlines()[0].strip() if text else "unknown"


def compile_stage(glslang: str, src: pathlib.Path, stage: str, extra: list[str]) -> bytes:
    with tempfile.TemporaryDirectory() as tmp:
        out_spv = pathlib.Path(tmp) / f"{src.stem}.{stage}.spv"
        cmd = [glslang, "-V", "--target-env", "vulkan1.3", "-S", stage, *extra, "-o", str(out_spv), str(src)]
        res = subprocess.run(cmd, capture_output=True, text=True)
        if res.returncode != 0:
            raise RuntimeError(f"glslangValidator failed for {src.name} ({stage}):\n{res.stdout}\n{res.stderr}")
        data = out_spv.read_bytes()
    if len(data) < 20 or len(data) % 4 != 0:
        raise RuntimeError(f"invalid SPIR-V size {len(data)} for {src.name} ({stage})")
    magic, ver = struct.unpack_from("<II", data, 0)
    if magic != 0x07230203:
        raise RuntimeError(f"bad SPIR-V magic 0x{magic:08x} for {src.name} ({stage})")
    return data


def validate_spv(spirv_val: str | None, name: str, data: bytes) -> None:
    if len(data) < 20 or len(data) % 4 != 0:
        raise RuntimeError(f"{name}: invalid SPIR-V length {len(data)}")
    magic = struct.unpack_from("<I", data, 0)[0]
    if magic != 0x07230203:
        raise RuntimeError(f"{name}: invalid SPIR-V magic 0x{magic:08x}")
    if not spirv_val:
        return
    with tempfile.TemporaryDirectory() as tmp:
        p = pathlib.Path(tmp) / f"{name}.spv"
        p.write_bytes(data)
        res = subprocess.run([spirv_val, "--target-env", "vulkan1.3", str(p)], capture_output=True, text=True)
        if res.returncode != 0:
            raise RuntimeError(f"spirv-val failed for {name}:\n{res.stdout}\n{res.stderr}")


def sha256_file(path: pathlib.Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def format_spv_hex(name: str, data: bytes) -> str:
    hex_str = data.hex()
    lines = [f"private def {name}Hex : Array String := #["]
    chunk_chars = 128  # 64 bytes per line
    for i in range(0, len(hex_str), chunk_chars):
        comma = "," if i + chunk_chars < len(hex_str) else ""
        lines.append(f'  "{hex_str[i : i + chunk_chars]}"{comma}')
    lines.append("]")
    lines.append("")
    lines.append(f"def {name} (_ : Unit := ()) : ByteArray := hexChunksToBytes {name}Hex")
    return "\n".join(lines)


def render_lean(version: str, blobs: dict[str, bytes]) -> str:
    scene_sha = sha256_file(SHADERS_DIR / "scene_sdf.glsl")
    blur_sha = sha256_file(SHADERS_DIR / "blur_box.comp.glsl")
    parts = [
        "/-!",
        "# LeanUI.Shaders — Precompiled Vulkan 1.3 SPIR-V shader modules",
        "",
        "Generated by `scripts/gen_leanui_shaders.py`; do not edit by hand.",
        f"Compiler: {version}",
        f"scene_sdf.glsl sha256: {scene_sha}",
        f"blur_box.comp.glsl sha256: {blur_sha}",
        "-/",
        "namespace LeanUI.Shaders",
        "",
        f'def compilerVersion : String := "{version}"',
        f'def sceneSdfSha256 : String := "{scene_sha}"',
        f'def blurBoxSha256 : String := "{blur_sha}"',
        "",
        "private def hexVal (b : UInt8) : UInt8 :=",
        "  if b >= 48 && b <= 57 then b - 48",
        "  else if b >= 97 && b <= 102 then b - 87",
        "  else if b >= 65 && b <= 70 then b - 55",
        "  else 0",
        "",
        "private def hexChunksToBytes (chunks : Array String) : ByteArray := Id.run do",
        "  let mut total := 0",
        "  for c in chunks do total := total + c.utf8ByteSize / 2",
        "  let mut out := ByteArray.emptyWithCapacity total",
        "  for c in chunks do",
        "    let bytes := c.toUTF8",
        "    let mut i := 0",
        "    while i + 1 < bytes.size do",
        "      let hi := hexVal (bytes.get! i)",
        "      let lo := hexVal (bytes.get! (i + 1))",
        "      out := out.push ((hi <<< 4) ||| lo)",
        "      i := i + 2",
        "  return out",
        "",
    ]
    for name, _, _, _ in STAGES:
        parts.append(format_spv_hex(name, blobs[name]))
        parts.append("")
    parts.append("end LeanUI.Shaders")
    return "\n".join(parts) + "\n"


def parse_existing_lean(text: str) -> tuple[str, str, str, dict[str, bytes]]:
    def grab_str(ident: str) -> str:
        m = re.search(rf'def {ident} : String := "([^"]*)"', text)
        if not m:
            raise RuntimeError(f"missing {ident} in {OUT_LEAN}")
        return m.group(1)

    ver = grab_str("compilerVersion")
    scene_sha = grab_str("sceneSdfSha256")
    blur_sha = grab_str("blurBoxSha256")
    blobs: dict[str, bytes] = {}
    for name, _, _, _ in STAGES:
        m = re.search(rf"def {name}Hex : Array String := #\[(.*?)\]", text, re.S)
        if not m:
            raise RuntimeError(f"missing {name}Hex in {OUT_LEAN}")
        hex_str = "".join(re.findall(r'"([0-9a-fA-F]+)"', m.group(1)))
        blobs[name] = bytes.fromhex(hex_str)
    return ver, scene_sha, blur_sha, blobs


def main() -> int:
    check = "--check" in sys.argv
    glslang = find_tool("glslangValidator", "/nix/store/*glslang*-bin/bin/glslangValidator")
    spirv_val = find_tool("spirv-val", "/nix/store/*spirv-tools*/bin/spirv-val")

    if check:
        if not OUT_LEAN.exists():
            sys.exit(f"{OUT_LEAN.relative_to(ROOT)} missing: run python3 scripts/gen_leanui_shaders.py")
        existing = OUT_LEAN.read_text()
        rec_ver, rec_scene_sha, rec_blur_sha, rec_blobs = parse_existing_lean(existing)
        cur_scene_sha = sha256_file(SHADERS_DIR / "scene_sdf.glsl")
        cur_blur_sha = sha256_file(SHADERS_DIR / "blur_box.comp.glsl")
        if rec_scene_sha != cur_scene_sha:
            sys.exit("shaders/scene_sdf.glsl changed without regenerating Shaders.lean")
        if rec_blur_sha != cur_blur_sha:
            sys.exit("shaders/blur_box.comp.glsl changed without regenerating Shaders.lean")
        for name, data in rec_blobs.items():
            validate_spv(spirv_val, f"embedded:{name}", data)
        if glslang:
            cur_ver = tool_version(glslang)
            fresh = {name: compile_stage(glslang, src, stage, extra) for name, src, stage, extra in STAGES}
            for name, data in fresh.items():
                validate_spv(spirv_val, f"compiled:{name}", data)
            if cur_ver == rec_ver:
                expected = render_lean(cur_ver, fresh)
                if existing != expected:
                    sys.exit("lean/OrbDesktop/LeanUI/Shaders.lean is stale: run python3 scripts/gen_leanui_shaders.py")
        print(f"LeanUI shaders check passed ({len(rec_blobs)} SPIR-V modules verified)")
        return 0

    if not glslang:
        sys.exit("glslangValidator not found (install glslang-tools)")
    ver = tool_version(glslang)
    blobs = {}
    for name, src, stage, extra in STAGES:
        data = compile_stage(glslang, src, stage, extra)
        validate_spv(spirv_val, name, data)
        blobs[name] = data
    OUT_LEAN.write_text(render_lean(ver, blobs))
    sizes = ", ".join(f"{k}={len(v)}B" for k, v in blobs.items())
    print(f"Generated {OUT_LEAN.relative_to(ROOT)} ({sizes}; {ver})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
